#!/usr/bin/env node
// Builds the static GitHub Pages site into docs/:
//   docs/index.html     the workbench, wrapped as a full page
//   docs/nj-lib.js      lib/ + data/ bundled for the browser (window.NJLookup)
//   docs/*.js           the engine and rules schema
// Lookups run in the visitor's browser against the state's public services; ordinance
// research uses the visitor's own Anthropic API key, stored only in their browser.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'docs');
const MODULES = [
  'lib/http.js', 'lib/geo.js', 'lib/nj-parcels.js', 'lib/nj-zoning.js', 'lib/nj-regional-zoning.js',
  'lib/nj-constraints.js', 'lib/pipeline.js', 'lib/research.js', 'lib/research-context.js', 'lib/browser.js',
  'public/rules-schema.js',
  'data/nj-municipalities.json', 'data/nj-zoning-links.json', 'data/nj-zoning-layers.json'
];

function bundle() {
  const defs = MODULES.map((rel) => {
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    const body = rel.endsWith('.json') ? `module.exports = ${JSON.stringify(JSON.parse(src))};` : src;
    return `${JSON.stringify(rel)}: function (module, exports, require) {\n${body}\n}`;
  });
  return `/* NJ Zoning Envelope browser bundle. Generated by scripts/build-pages.js; do not edit. */
(function () {
  'use strict';
  var defs = {\n${defs.join(',\n')}\n};
  var cache = {};
  function resolve(from, p) {
    var parts = from.split('/'); parts.pop();
    p.split('/').forEach(function (seg) { if (seg === '..') parts.pop(); else if (seg !== '.') parts.push(seg); });
    var r = parts.join('/');
    if (defs[r]) return r;
    if (defs[r + '.js']) return r + '.js';
    throw new Error('Module not bundled: ' + p + ' (from ' + from + ')');
  }
  function load(id) {
    if (cache[id]) return cache[id].exports;
    var module = { exports: {} }; cache[id] = module;
    defs[id](module, module.exports, function (p) { return load(resolve(id, p)); });
    return module.exports;
  }
  window.NJLookup = load('lib/browser.js');
})();
`;
}

function page() {
  let html = fs.readFileSync(path.join(ROOT, 'public', 'workbench.html'), 'utf8');
  html = html.replace('<script src="zoning-engine.js"></script>', '<script src="nj-lib.js"></script>\n<script src="zoning-engine.js"></script>');
  if (!html.includes('nj-lib.js')) throw new Error('Could not find the engine script tag in workbench.html');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="What can be built on a New Jersey property: parcel, zoning district, site constraints, comps and a buildout envelope.">
<style>[hidden]{display:none!important}body{margin:0}</style>
</head>
<body>
${html}
</body>
</html>
`;
}

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'nj-lib.js'), bundle());
fs.writeFileSync(path.join(OUT, 'index.html'), page());
for (const f of ['zoning-engine.js', 'rules-schema.js']) fs.copyFileSync(path.join(ROOT, 'public', f), path.join(OUT, f));
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
const kb = (f) => Math.round(fs.statSync(path.join(OUT, f)).size / 1024);
console.log(`docs/ built: index.html ${kb('index.html')} KB, nj-lib.js ${kb('nj-lib.js')} KB`);
